// `node scripts/promote.mjs --ref <40-hex sha> [--label <text>] [--since <git ref>] [--dry-run]`
//
// Renders this repo's own agent-facing workflows and skills from the released
// templates (templates/workflows/*.yml, skills/*), pinned to one commit. The
// last release runs the loop: the files under .github/workflows/ and
// .mergeproof/skills/ are never hand-edited copies that drift from what
// customers get. A maintainer script, not part of the published package.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseFlags } from '../src/args.mjs';
import { CONFIG_FILE, parseConfig } from '../src/config.mjs';
import { UsageError } from '../src/errors.mjs';
import { matchesAny } from '../src/glob.mjs';
import { EXIT_CODES } from '../src/verdict.mjs';
import { runProcess } from '../src/adapters/process.mjs';
import { fillTemplate } from '../src/commands/init.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SHA = /^[0-9a-f]{40}$/;
const USAGE = 'usage: node scripts/promote.mjs --ref <40-hex sha> [--label <text>] [--since <git ref>] [--dry-run]';
const INSTALL_NOTE = '# zero dependencies: nothing to install';
// Beyond the config's human-only and agent-instruction paths, these are the
// gate and the action itself: what a human re-reads before moving the pin.
const GATE_CODE = ['src/**', 'bin/**', 'action.yml'];

/**
 * Fill the template's placeholders for this repo and pin every mergeproof
 * reference to `ref`. Throws instead of returning a file that is not fully
 * pinned or still has a placeholder.
 */
export function renderWorkflow(text, { name, ref, label }) {
  if (!SHA.test(ref)) throw new Error(`ref must be a full 40-character commit sha, got "${ref}"`);
  if (!label || /[\r\n\0]/.test(label)) throw new Error('label must be a single line of text');
  const pin = `${ref} # ${label}`;

  let out = fillTemplate(text, { ciWorkflow: 'CI', installCommand: ':' });
  // Replacers are functions so a "$" in a label is never read as a pattern.
  out = out.replace(/ahmed-3m\/mergeproof@v1(?![\w.-])/g, () => `ahmed-3m/mergeproof@${pin}`);
  out = out.replace(/^( *)MERGEPROOF_REF: v1$/gm, (_, indent) => `${indent}MERGEPROOF_REF: ${pin}`);
  out = out.replace(/^( *run: ":")$/gm, (_, line) => `${line} ${INSTALL_NOTE}`);
  out = replaceInitNote(out, `# Generated by scripts/promote.mjs from templates/workflows/${name} at ${ref} (${label}). Edit the template and re-run promote; never edit this file by hand.`);

  for (const m of out.matchAll(/ahmed-3m\/mergeproof@([^\s'"]*)/g)) {
    if (m[1] !== ref) throw new Error(`${name}: "${m[0]}" is not pinned to ${ref}`);
  }
  for (const m of out.matchAll(/^[ \t]*MERGEPROOF_REF:(.*)$/gm)) {
    if (m[1] !== ` ${pin}`) throw new Error(`${name}: "${m[0].trim()}" is not pinned to ${ref}`);
  }
  const left = /\{\{[A-Z][A-Z0-9_]*\}\}/.exec(out);
  if (left) throw new Error(`${name}: placeholder ${left[0]} was not filled`);
  return out;
}

// The template's header paragraph about `mergeproof init` (it ends at the next
// bare "#" line or the first non-comment line) becomes the generated note.
function replaceInitNote(text, note) {
  const lines = text.split('\n');
  const start = lines.findIndex((l) => l.startsWith('#') && l.includes('`mergeproof init`'));
  if (start === -1) throw new Error('the template has no header line about `mergeproof init` to replace');
  let end = start + 1;
  while (end < lines.length && lines[end].startsWith('#') && lines[end].trimEnd() !== '#') end++;
  lines.splice(start, end - start, note);
  return lines.join('\n');
}

/** Every file under `dir` as a sorted list of '/'-separated paths relative to it. */
function listFiles(dir, prefix = '') {
  const out = [];
  for (const e of readdirSync(join(dir, prefix), { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...listFiles(dir, rel));
    else if (e.isFile()) out.push(rel);
  }
  return out.sort();
}

/** Remove directories left empty under `dir` (deepest first), never `dir` itself. */
function pruneEmpty(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (!e.isDirectory()) continue;
    pruneEmpty(join(dir, e.name));
    if (readdirSync(join(dir, e.name)).length === 0) rmSync(join(dir, e.name), { recursive: true });
  }
}

function gitOut(run, root, args) {
  const res = run('git', args, { cwd: root });
  return res.code === 0 ? res.stdout.trim() : null;
}

/**
 * Render workflows and copy skills into `root`, then list the gate paths that
 * changed since the previous release. `deps.log` receives one line per call;
 * `deps.run` is `runProcess` (swapped in tests).
 */
export function promote(opts, deps = {}) {
  const { ref, label: givenLabel = null, since: givenSince = null, dryRun = false, root = ROOT } = opts;
  const log = deps.log ?? ((line) => console.log(line));
  const run = deps.run ?? runProcess;

  if (!ref) throw new UsageError('--ref <40-hex sha> is required');
  if (!SHA.test(ref)) throw new UsageError(`--ref must be a full 40-character commit sha (a tag or branch is not an immutable pin), got "${ref}"`);
  if (givenSince !== null && givenSince.startsWith('-')) throw new UsageError('--since must be a git ref');

  if (gitOut(run, root, ['cat-file', '-e', `${ref}^{commit}`]) === null) throw new Error(`commit ${ref} is not in this repository`);
  const label = givenLabel ?? gitOut(run, root, ['describe', '--tags', '--exact-match', ref]) ?? 'main';
  // The files are read from the working tree but labelled "at <ref>": refuse
  // unless they are exactly what <ref> holds, so the pin never lies.
  const drift = run('git', ['diff', '--name-only', ref, '--', 'templates/workflows', 'skills'], { cwd: root });
  if (drift.code !== 0) throw new Error(`git diff ${ref} failed: ${drift.stderr.trim().split('\n')[0]}`);
  const drifted = drift.stdout.split('\n').map((l) => l.trim()).filter(Boolean);
  if (drifted.length > 0) throw new Error(`${drifted[0]} differs from ${ref}; check out ${ref} (or commit) before promoting`);
  const untracked = gitOut(run, root, ['ls-files', '--others', '--exclude-standard', '--', 'templates/workflows', 'skills']);
  if (untracked) throw new Error(`${untracked.split('\n')[0]} is not in ${ref}; check out ${ref} before promoting`);

  const changes = [];
  const settle = (rel, content) => {
    const file = join(root, rel);
    const same = existsSync(file) && readFileSync(file).equals(content);
    if (same) return log(`unchanged ${rel}`);
    if (!dryRun) {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, content);
    }
    changes.push(rel);
    log(`${dryRun ? 'would update' : 'updated'} ${rel}`);
  };

  // Only files that have a template are touched: ci.yml, main-guard.yml and
  // release.yml are this repo's own and have none.
  const templates = join(root, 'templates', 'workflows');
  for (const name of readdirSync(templates).filter((n) => n.endsWith('.yml')).sort()) {
    const text = renderWorkflow(readFileSync(join(templates, name), 'utf8'), { name, ref, label });
    settle(`.github/workflows/${name}`, Buffer.from(text, 'utf8'));
  }

  // Skills are copied byte for byte; a file removed from skills/<name> must
  // not linger in the copy, or the repo would run a skill nobody ships.
  const skills = join(root, 'skills');
  for (const dir of readdirSync(skills, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort()) {
    const source = join(skills, dir);
    const target = join(root, '.mergeproof', 'skills', dir);
    const wanted = listFiles(source);
    for (const rel of wanted) settle(`.mergeproof/skills/${dir}/${rel}`, readFileSync(join(source, rel)));
    for (const rel of existsSync(target) ? listFiles(target) : []) {
      if (wanted.includes(rel)) continue;
      if (!dryRun) rmSync(join(target, rel));
      changes.push(`.mergeproof/skills/${dir}/${rel}`);
      log(`${dryRun ? 'would remove' : 'removed'} .mergeproof/skills/${dir}/${rel}`);
    }
    if (!dryRun && existsSync(target)) pruneEmpty(target);
  }

  const since = givenSince ?? gitOut(run, root, ['describe', '--tags', '--abbrev=0', '--match', 'v[0-9]*', `${ref}^`]);
  if (since === null) {
    log('no previous release tag; pass --since <ref>');
  } else {
    const diff = run('git', ['diff', '--name-only', `${since}..${ref}`], { cwd: root });
    if (diff.code !== 0) throw new Error(`git diff ${since}..${ref} failed: ${diff.stderr.trim().split('\n')[0]}`);
    const configFile = join(root, CONFIG_FILE);
    const config = parseConfig(existsSync(configFile) ? readFileSync(configFile, 'utf8') : null, configFile);
    // humanOnly is absent from configs older than that setting.
    const patterns = [...(config.paths.humanOnly ?? []), ...config.paths.agentInstructions, ...GATE_CODE];
    const gate = diff.stdout.split('\n').map((l) => l.trim()).filter((p) => p && matchesAny(p, patterns));
    log(`gate code changed since ${since}:`);
    for (const p of gate) log(p);
    if (gate.length === 0) log('(none)');
  }
  return { changes, label };
}

function main(argv) {
  try {
    const { positionals, flags } = parseFlags(argv, ['dry-run'], ['ref', 'label', 'since']);
    if (positionals.length > 0) throw new UsageError(`unexpected argument: ${positionals[0]}`);
    promote({ ref: flags.ref, label: flags.label, since: flags.since, dryRun: flags['dry-run'] });
    return 0;
  } catch (err) {
    if (err instanceof UsageError) {
      console.error(`promote: ${err.message}\n${USAGE}`);
      return EXIT_CODES.USAGE;
    }
    console.error(`promote: ${String(err.message ?? err).split('\n')[0]}`);
    return EXIT_CODES.ERROR;
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exit(main(process.argv.slice(2)));
}
