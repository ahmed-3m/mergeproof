// scripts/promote.mjs: renders this repo's workflows and skills from the
// templates at a pinned commit. Everything runs in a temp copy of the
// templates and skills with a real throwaway git repo (for the tag lookups and
// the gate-path list); nothing touches this repo's own .github or .mergeproof.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { promote, renderWorkflow } from '../scripts/promote.mjs';
import { UsageError } from '../src/errors.mjs';

const SCRIPT = resolve('scripts/promote.mjs');
const WORKFLOWS = ['mergeproof-pr.yml', 'mergeproof-sync.yml', 'mergeproof-issue.yml'];
const template = (name) => readFileSync(resolve('templates/workflows', name), 'utf8');
const SHA = 'a'.repeat(40);

function makeRepo() {
  const dir = mkdtempSync(join(tmpdir(), 'mp-promote-'));
  const git = (...args) => {
    const res = spawnSync('git', ['-c', 'user.name=t', '-c', 'user.email=t@example.com', '-c', 'commit.gpgsign=false', ...args], { cwd: dir, encoding: 'utf8' });
    if (res.status !== 0) throw new Error(`git ${args.join(' ')}: ${res.stderr}`);
    return res.stdout.trim();
  };
  const write = (rel, content) => {
    mkdirSync(dirname(join(dir, rel)), { recursive: true });
    writeFileSync(join(dir, rel), content);
  };
  cpSync(resolve('templates'), join(dir, 'templates'), { recursive: true });
  cpSync(resolve('skills'), join(dir, 'skills'), { recursive: true });
  cpSync(resolve('.mergeproof.json'), join(dir, '.mergeproof.json'));
  write('.github/workflows/ci.yml', 'name: CI\n');
  write('.github/workflows/release.yml', 'name: release\n');
  write('src/decide.mjs', '// v1\n');
  write('README.md', 'one\n');
  git('init', '--quiet', '--initial-branch=main');
  git('add', '-A');
  git('commit', '--quiet', '-m', 'first');
  git('tag', 'v0.0.1');
  write('src/decide.mjs', '// v2\n');
  write('README.md', 'two\n');
  git('commit', '--quiet', '-am', 'second');
  return { dir, git, write, ref: git('rev-parse', 'HEAD'), cleanup: () => rmSync(dir, { recursive: true, force: true }) };
}

/** Run promote in a fresh temp repo; hand the repo, the helper and the printed lines to `fn`. */
function withRepo(fn) {
  const repo = makeRepo();
  try {
    const run = (opts = {}) => {
      const lines = [];
      const result = promote({ ref: repo.git('rev-parse', 'HEAD'), root: repo.dir, ...opts }, { log: (l) => lines.push(l) });
      return { lines, result };
    };
    return fn(repo, run);
  } finally {
    repo.cleanup();
  }
}

/** Every file under `dir` (relative, '/'-separated) with its bytes, to compare two trees. */
function snapshot(dir, prefix = '') {
  const out = {};
  for (const e of readdirSync(join(dir, prefix), { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${e.name}` : e.name;
    if (e.isDirectory()) Object.assign(out, snapshot(dir, rel));
    else out[rel] = readFileSync(join(dir, rel)).toString('base64');
  }
  return out;
}

test('renderWorkflow fills the placeholders and pins every mergeproof reference to the ref and label', () => {
  for (const name of WORKFLOWS) {
    const out = renderWorkflow(template(name), { name, ref: SHA, label: 'v0.0.1' });
    assert.doesNotMatch(out, /\{\{[A-Z][A-Z0-9_]*\}\}/, `${name}: no placeholder left`);
    assert.doesNotMatch(out, /ahmed-3m\/mergeproof@v1/, `${name}: the floating tag is gone`);
    assert.ok(out.includes(`ahmed-3m/mergeproof@${SHA} # v0.0.1`) || name === 'mergeproof-issue.yml', `${name}: action pinned with its label`);
  }
  const pr = renderWorkflow(template('mergeproof-pr.yml'), { name: 'mergeproof-pr.yml', ref: SHA, label: 'v0.0.1' });
  assert.match(pr, /workflows: \["CI"\]/);
  assert.match(pr, /^ +run: ":" # zero dependencies: nothing to install$/m);
  assert.equal(pr.match(/ahmed-3m\/mergeproof@/g).length, 2, 'gate and apply both use the action');
  const issue = renderWorkflow(template('mergeproof-issue.yml'), { name: 'mergeproof-issue.yml', ref: SHA, label: 'v0.0.1' });
  assert.match(issue, new RegExp(`^  MERGEPROOF_REF: ${SHA} # v0\\.0\\.1$`, 'm'), 'the checkout the container mounts is pinned too');
  assert.match(issue, /MERGEPROOF_INSTALL_COMMAND: ":"/);
  assert.match(issue, /ref: \$\{\{ env\.MERGEPROOF_REF \}\}/, 'GitHub expressions survive untouched');
});

test('renderWorkflow replaces the template\'s init note with the generated header and keeps the rest', () => {
  const name = 'mergeproof-pr.yml';
  const out = renderWorkflow(template(name), { name, ref: SHA, label: 'v0.0.1' });
  const header = `# Generated by scripts/promote.mjs from templates/workflows/${name} at ${SHA} (v0.0.1). Edit the template and re-run promote; never edit this file by hand.`;
  assert.equal(out.split('\n').filter((l) => l === header).length, 1);
  assert.doesNotMatch(out, /mergeproof init/);
  assert.match(out, /^# Mergeproof — PR to outcome \(flow 3\)\.$/m, 'the template\'s own header stays');
  assert.match(out, /^# Triggered by workflow_run, never pull_request/m);
  const sync = renderWorkflow(template('mergeproof-sync.yml'), { name: 'mergeproof-sync.yml', ref: SHA, label: 'main' });
  assert.match(sync, /^# Generated by scripts\/promote\.mjs from templates\/workflows\/mergeproof-sync\.yml at a{40} \(main\)\./m);
});

test('renderWorkflow refuses a leftover placeholder, an unpinned reference or a ref that is not a sha', () => {
  const base = 'name: x\n# `mergeproof init` fills this\njobs:\n  a:\n    steps:\n      - uses: ahmed-3m/mergeproof@v1\n';
  const args = { name: 'x.yml', ref: SHA, label: 'main' };
  assert.doesNotThrow(() => renderWorkflow(base, args));
  assert.throws(() => renderWorkflow(`${base}      - run: "{{SOMETHING_ELSE}}"\n`, args), /\{\{SOMETHING_ELSE\}\}/);
  assert.throws(() => renderWorkflow(`${base}      - uses: ahmed-3m/mergeproof@main\n`, args), /not pinned/);
  assert.throws(() => renderWorkflow(`${base}      - uses: ahmed-3m/mergeproof@v1.2\n`, args), /not pinned/);
  assert.throws(() => renderWorkflow(`${base}env:\n  MERGEPROOF_REF: main\n`, args), /MERGEPROOF_REF/);
  assert.throws(() => renderWorkflow(base, { ...args, ref: 'v1' }), /40-character/);
  assert.throws(() => renderWorkflow('name: x\n', args), /mergeproof init/, 'a template without the init note cannot get the generated header');
  assert.throws(() => renderWorkflow(base, { ...args, label: 'a\nb' }), /single line/);
});

test('promote rejects a --ref that is not a full 40-hex sha as a usage error', () => {
  withRepo((repo, run) => {
    for (const ref of [undefined, '', 'v1', 'main', 'abc123', 'A'.repeat(40), `${repo.ref}0`]) {
      assert.throws(() => run({ ref }), UsageError, String(ref));
    }
    assert.throws(() => run({ since: '--output=x' }), UsageError);
    assert.deepEqual(readdirSync(join(repo.dir, '.github', 'workflows')).sort(), ['ci.yml', 'release.yml'], 'nothing was written');
  });
});

test('the script exits 2 on a bad --ref, 1 on an unknown commit, and prints no stack trace', () => {
  const bad = spawnSync(process.execPath, [SCRIPT, '--ref', 'v1'], { encoding: 'utf8' });
  assert.equal(bad.status, 2);
  assert.match(bad.stderr, /^promote: --ref must be a full 40-character commit sha/);
  assert.doesNotMatch(bad.stderr, /\bat .*\.mjs:\d+/);
  const missing = spawnSync(process.execPath, [SCRIPT], { encoding: 'utf8' });
  assert.equal(missing.status, 2);
  const unknown = spawnSync(process.execPath, [SCRIPT, '--ref', 'f'.repeat(40), '--dry-run'], { encoding: 'utf8' });
  assert.equal(unknown.status, 1);
  assert.equal(unknown.stderr.trim().split('\n').length, 1, 'one line');
  assert.match(unknown.stderr, /^promote: commit f{40} is not in this repository/);
});

test('promote renders every template into .github/workflows pinned to the ref, labelled by the tag on it', () => {
  withRepo((repo, run) => {
    repo.git('tag', 'v0.0.2');
    const { lines, result } = run();
    assert.equal(result.label, 'v0.0.2');
    for (const name of WORKFLOWS) {
      assert.ok(lines.includes(`updated .github/workflows/${name}`), name);
      const text = readFileSync(join(repo.dir, '.github', 'workflows', name), 'utf8');
      assert.equal(text, renderWorkflow(template(name), { name, ref: repo.ref, label: 'v0.0.2' }));
    }
    assert.match(readFileSync(join(repo.dir, '.github', 'workflows', 'mergeproof-pr.yml'), 'utf8'), new RegExp(`ahmed-3m/mergeproof@${repo.ref} # v0\\.0\\.2`));
  });
});

test('the label is --label when given and main when the ref carries no tag', () => {
  withRepo((repo, run) => {
    assert.equal(run({ dryRun: true }).result.label, 'main');
    assert.equal(run({ dryRun: true, label: 'rc 1' }).result.label, 'rc 1');
  });
});

test('--dry-run writes nothing and says what would change', () => {
  withRepo((repo, run) => {
    const before = snapshot(repo.dir);
    const { lines } = run({ dryRun: true });
    assert.deepEqual(snapshot(repo.dir), before);
    assert.ok(lines.includes('would update .github/workflows/mergeproof-pr.yml'));
    assert.ok(lines.includes('would update .mergeproof/skills/bugfix/SKILL.md'));
    assert.ok(!lines.some((l) => l.startsWith('updated ')));
    assert.ok(!existsSync(join(repo.dir, '.mergeproof')));
  });
});

test('a second run changes nothing and reports every file unchanged', () => {
  withRepo((repo, run) => {
    run();
    const before = snapshot(repo.dir);
    const { lines } = run();
    assert.deepEqual(snapshot(repo.dir), before);
    const files = lines.filter((l) => /^(updated|unchanged|would update|removed) /.test(l));
    assert.ok(files.length >= WORKFLOWS.length + 2);
    assert.ok(files.every((l) => l.startsWith('unchanged ')), files.join('\n'));
  });
});

test('skills are copied byte for byte and a file removed from skills/<name> leaves the copy', () => {
  withRepo((repo, run) => {
    const bytes = Buffer.from([0x68, 0x69, 0x0d, 0x0a, 0xff, 0x00, 0x80, 0x0a]);
    writeFileSync(join(repo.dir, 'skills', 'bugfix', 'extra.bin'), bytes);
    mkdirSync(join(repo.dir, 'skills', 'bugfix', 'nested'));
    writeFileSync(join(repo.dir, 'skills', 'bugfix', 'nested', 'note.md'), 'n\r\n');
    repo.git('add', '-A', 'skills');
    repo.git('commit', '--quiet', '-m', 'more skill files');
    run();
    for (const skill of ['bugfix', 'feature']) {
      assert.ok(readFileSync(join(repo.dir, 'skills', skill, 'SKILL.md')).equals(readFileSync(join(repo.dir, '.mergeproof', 'skills', skill, 'SKILL.md'))));
    }
    assert.ok(readFileSync(join(repo.dir, '.mergeproof', 'skills', 'bugfix', 'extra.bin')).equals(bytes));
    assert.ok(existsSync(join(repo.dir, '.mergeproof', 'skills', 'bugfix', 'nested', 'note.md')));
    assert.ok(!existsSync(join(repo.dir, '.mergeproof', 'skills', 'README.md')), 'a file directly under skills/ is not a skill');

    rmSync(join(repo.dir, 'skills', 'bugfix', 'extra.bin'));
    rmSync(join(repo.dir, 'skills', 'bugfix', 'nested'), { recursive: true });
    repo.git('commit', '--quiet', '-am', 'fewer skill files');
    const { lines } = run();
    assert.ok(lines.includes('removed .mergeproof/skills/bugfix/extra.bin'));
    assert.ok(!existsSync(join(repo.dir, '.mergeproof', 'skills', 'bugfix', 'extra.bin')));
    assert.ok(!existsSync(join(repo.dir, '.mergeproof', 'skills', 'bugfix', 'nested')), 'the emptied directory goes too');
    assert.ok(existsSync(join(repo.dir, '.mergeproof', 'skills', 'bugfix', 'SKILL.md')));
  });
});

test('a template or skill that differs from --ref is refused before anything is written', () => {
  withRepo((repo, run) => {
    // git refreshes its own index while checking, so compare the outputs only.
    const outputs = () => ({ ...snapshot(join(repo.dir, '.github')), ...(existsSync(join(repo.dir, '.mergeproof', 'skills')) ? snapshot(join(repo.dir, '.mergeproof', 'skills')) : {}) });
    const before = outputs();
    repo.write('templates/workflows/mergeproof-pr.yml', template('mergeproof-pr.yml') + '# local edit\n');
    assert.throws(() => run(), /mergeproof-pr\.yml differs from/);
    repo.git('checkout', '--', 'templates');
    repo.write('skills/bugfix/new.md', 'x\n');
    assert.throws(() => run(), /skills\/bugfix\/new\.md is not in/);
    rmSync(join(repo.dir, 'skills', 'bugfix', 'new.md'));
    assert.deepEqual(outputs(), before);
  });
});

test('workflows without a template are never touched', () => {
  withRepo((repo, run) => {
    repo.write('.github/workflows/main-guard.yml', 'name: guard\n');
    run();
    assert.equal(readFileSync(join(repo.dir, '.github', 'workflows', 'ci.yml'), 'utf8'), 'name: CI\n');
    assert.equal(readFileSync(join(repo.dir, '.github', 'workflows', 'release.yml'), 'utf8'), 'name: release\n');
    assert.equal(readFileSync(join(repo.dir, '.github', 'workflows', 'main-guard.yml'), 'utf8'), 'name: guard\n');
    const rendered = readdirSync(resolve('templates/workflows')).filter((n) => n.endsWith('.yml'));
    assert.deepEqual(readdirSync(join(repo.dir, '.github', 'workflows')).sort(), ['ci.yml', 'main-guard.yml', 'release.yml', ...rendered].sort());
  });
});

test('the gate-path list names changed gate code since the previous release tag and skips other files', () => {
  withRepo((repo, run) => {
    const { lines } = run({ dryRun: true });
    const at = lines.indexOf('gate code changed since v0.0.1:');
    assert.ok(at !== -1, lines.join('\n'));
    const listed = lines.slice(at + 1);
    assert.ok(listed.includes('src/decide.mjs'));
    assert.ok(!listed.includes('README.md'));
  });
});

test('--since overrides the previous tag, and a repo without a release tag says so', () => {
  withRepo((repo, run) => {
    const first = repo.git('rev-list', '--max-parents=0', 'HEAD');
    const { lines } = run({ dryRun: true, since: first });
    assert.ok(lines.includes(`gate code changed since ${first}:`));
    assert.ok(lines.includes('src/decide.mjs'));
    repo.git('tag', '-d', 'v0.0.1');
    const none = run({ dryRun: true }).lines;
    assert.ok(none.includes('no previous release tag; pass --since <ref>'));
    assert.ok(!none.some((l) => l.startsWith('gate code changed since')));
  });
});

test('the gate-path list also covers the agent-instruction paths and says when nothing matches', () => {
  withRepo((repo, run) => {
    repo.write('skills/feature/SKILL.md', 'changed\n');
    repo.write('bin/mergeproof.mjs', '// bin\n');
    repo.write('action.yml', 'name: a\n');
    repo.git('add', '-A');
    repo.git('commit', '--quiet', '-m', 'third');
    const sha = repo.git('rev-parse', 'HEAD');
    const listed = run({ ref: sha, dryRun: true }).lines;
    for (const p of ['skills/feature/SKILL.md', 'bin/mergeproof.mjs', 'action.yml', 'src/decide.mjs']) assert.ok(listed.includes(p), p);
    assert.ok(!listed.includes('README.md'));
    const quiet = run({ ref: sha, dryRun: true, since: sha }).lines;
    assert.deepEqual(quiet.slice(quiet.indexOf(`gate code changed since ${sha}:`) + 1), ['(none)']);
  });
});
